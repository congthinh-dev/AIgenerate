import express from "express";
import { errorHandler } from "./middleware/errors.js";
import { requireAuth } from "./middleware/auth.js";
import { authRouter } from "./modules/auth/routes.js";
import { resourceRouter } from "./modules/resources/routes.js";
import { bookingRouter } from "./modules/bookings/routes.js";
import { calendarRouter } from "./modules/calendar/routes.js";
import { adminRouter } from "./modules/admin/routes.js";
export const app = express();
app.disable("x-powered-by");
app.use(express.json({ limit: "32kb" }));
app.get("/api/health", (_req, res) => res.json({ status: "ok" }));
app.use("/api/v1/auth", authRouter);
app.use("/api/v1/resources", resourceRouter);
app.use("/api/v1/bookings", bookingRouter);
app.use("/api/v1/calendar", calendarRouter);
app.use("/api/v1/admin", requireAuth, adminRouter);
app.use((_req, res) => res.status(404).json({ error: { code: "NOT_FOUND", message: "Route was not found." } }));
app.use(errorHandler);
